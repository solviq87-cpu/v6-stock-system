/**
 * 用户提供的 A 股短线研究规则。每条条件描述的是应由证据证实的事实。
 * advice 保存规则原意，仅供模拟研究使用；强弱、仓位和方向用语不构成订单。
 * fact 为本地指标适配器的可选键。无适配键或证据不足的条件保持未知。
 */
function clause(label, level, logic, advice, criteria) {
  return { label, logic, level, advice, criteria };
}

function rule(id, name, kind, ...clauses) {
  let nextCriterion = 1;
  return {
    id,
    name,
    kind,
    clauses: clauses.map(({ criteria, ...branch }) => ({
      ...branch,
      criteria: criteria.map(item => {
        const [label, fact] = Array.isArray(item) ? item : [item];
        return { id: `${id}.${nextCriterion++}`, label, ...(fact ? { fact } : {}) };
      }),
    })),
  };
}

function strategy(id, name, criteria, advice = '标记为该模式的研究候选，保留证据以供复盘。') {
  return rule(id, name, 'strategy', clause('模式条件', 'match', 'all', advice, criteria));
}

function risk(id, name, criteria, advice, { logic = 'all', level = 'block' } = {}) {
  return rule(id, name, 'risk', clause('规避条件', level, logic, advice, criteria));
}

function index(id, name, criteria, advice, level = 'warn') {
  return rule(id, name, 'index', clause('指数环境', level, 'all', advice, criteria));
}

