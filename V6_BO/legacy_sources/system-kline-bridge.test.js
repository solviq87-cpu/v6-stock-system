 'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {toResearchStock}=require('../src/strategy/system-kline-bridge');
const {scanUniverse}=require('../src/strategy/universe-scanner');
const server=fs.readFileSync(path.join(__dirname,'../server.js'),'utf8');
let n=0;const ok=x=>{assert.ok(x);n++};
const rows=Array.from({length:40},(_,i)=>{const d=new Date(Date.UTC(2026,8,1+i));const c=10+i*.1;return {date:d.toISOString().slice(0,10),open:c,high:c+.2,low:c-.2,close:c,volume:1000000};});
