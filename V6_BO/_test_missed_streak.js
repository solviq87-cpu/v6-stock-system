// 锁死「补漏票连板数派生」deriveStreakFromRows（2026-10-19 iv+1 轮）。
// 背景：iv 轮补漏票 limitUpCount/streak 写死 null/1，用户「13」要求连板数从 K 线派生。
//   deriveStreakFromRows 纯函数：从 K 线算「今天涨停」的连板数。
// 铁律：今天涨停是新浪快照确认的已知事实（price=精确涨停价），连板数≥1；
//   K 线源可能延迟（最后一天≠今天），这时「今天涨停」要手动 +1。
const fs = require('fs');
const A = require('./analysis.js');

// 从 server.js 抠出 deriveStreakFromRows 函数体，用 new Function 真跑（与生产同一份源码）
const src = fs.readFileSync(__dirname + '/server.js', 'utf8');
const m = src.match(/function deriveStreakFromRows\(rows, code, name, today\) \{[\s\S]*?\n\}/);
if (!m) { console.log('❌ deriveStreakFromRows 函数体未找到'); process.exit(1); }
const fn = new Function('A', `return (${m[0]});`)(A);

let pass = 0, fail = 0;
const ok = (c, n, got) => { if (c) { pass++; console.log('  ✅ ' + n + (got !== undefined ? '  → ' + got : '')); } else { fail++; console.log('  ❌ ' + n + '  → ' + got); } };
const sec = t => console.log('\n' + t);

// 造 K 线（主板 600000，限幅 10%，tol=0.3 → pct>=9.7 算涨停）
function k(pct, date) { return { date, open: 10, high: 11, low: 9, close: 10, pct }; }

sec('① 无 K 线 / 空 rows → 首板 1（今天涨停是事实，不拿 0 冒充）');
{
  ok(fn(null, '603337', '杰克科技', '20261019') === 1, 'rows=null → 1');
  ok(fn([], '603337', '杰克科技', '20261019') === 1, 'rows=[] → 1');
  ok(fn(undefined, '603337', '杰克科技', '20261019') === 1, 'rows=undefined → 1');
}

sec('② 最后一天就是今天：从今天这根往回数（含今天）');
{
  // 今天 + 昨天 + 前天 都涨停 → 3 连板
  const rows = [k(10, '2026-10-15'), k(10, '2026-10-16'), k(10, '2026-10-19')];
  ok(fn(rows, '600000', '浦发银行', '2026-10-19') === 3, '连续3涨停(含今天) → 3', fn(rows, '600000', '浦发银行', '2026-10-19'));
  // 只有今天涨停 → 1
  const r2 = [k(-1, '2026-10-16'), k(10, '2026-10-19')];
  ok(fn(r2, '600000', '浦发银行', '2026-10-19') === 1, '只有今天涨停 → 1', fn(r2, '600000', '浦发银行', '2026-10-19'));
}

sec('③ 最后一天是今天但今天这根非涨停（K线盘中快照未更新）→ 至少 1');
{
  const rows = [k(10, '2026-10-16'), k(2, '2026-10-19')];  // 今天这根 pct=2（盘中，未涨停）
  ok(fn(rows, '600000', '浦发银行', '2026-10-19') === 1, '今天K线未涨停 → max(0,1)=1', fn(rows, '600000', '浦发银行', '2026-10-19'));
}

sec('④ 最后一天是昨天（K线源延迟）：连板 = 昨天起往回数 + 1');
{
  // 昨天非涨停 → 0+1=1（杰克科技实况：10-16 收 +0.61%，今天首板）
  const rows = [k(-6.68, '2026-10-15'), k(0.61, '2026-10-16')];
  ok(fn(rows, '603337', '杰克科技', '2026-10-19') === 1, '昨天非涨停 → 今天首板 1', fn(rows, '603337', '杰克科技', '2026-10-19'));
  // 昨天+前天都涨停（两源连续漏板）→ 2+1=3
  const r2 = [k(10, '2026-10-15'), k(10, '2026-10-16')];
  ok(fn(r2, '600000', '浦发银行', '2026-10-19') === 3, '昨天前天都涨停 → 今天3连板', fn(r2, '600000', '浦发银行', '2026-10-19'));
  // 昨天涨停前天非 → 1+1=2
  const r3 = [k(-1, '2026-10-15'), k(10, '2026-10-16')];
  ok(fn(r3, '600000', '浦发银行', '2026-10-19') === 2, '昨天涨停前天非 → 今天2连板', fn(r3, '600000', '浦发银行', '2026-10-19'));
}

sec('⑤ today 为空（拿不到归属日）→ 退化为「最后一天起往回数 + 1」');
{
  const rows = [k(10, '2026-10-15'), k(10, '2026-10-16')];
  ok(fn(rows, '600000', '浦发银行', '') === 3, 'today 空 → 仍按延迟口径 +1', fn(rows, '600000', '浦发银行', ''));
}

sec('⑥ 分板块限幅：创业板 20% 连板数不被 10% 口径数错');
{
  // 创业板 300xxx，限幅 20%，tol=0.3 → pct>=19.7 算涨停
  const rows = [k(20, '2026-10-16'), k(20, '2026-10-19')];  // 昨天今天都 20cm 涨停
  ok(fn(rows, '300000', '创业票', '2026-10-19') === 2, '创业板20cm连续2板 → 2', fn(rows, '300000', '创业票', '2026-10-19'));
  // 创业板涨 10%（非涨停）不能被数成板
  const r2 = [k(10, '2026-10-16')];
  ok(fn(r2, '300000', '创业票', '2026-10-19') === 1, '创业板涨10%(非20cm) → 昨天不算板，今天1', fn(r2, '300000', '创业票', '2026-10-19'));
}

console.log(`\n结果：${pass} 通过 / ${fail} 失败`);
process.exit(fail ? 1 : 0);
