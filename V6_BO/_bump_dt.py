TARGETS = [("server.js", "const APP_VER = "), ("public/index.html", "const APP_VER = ")]

for path, prefix in TARGETS:
    with io.open(path, "r", encoding="utf-8", newline="") as f:
        lines = f.read().split("\n")
    hit = -1
    for i, l in enumerate(lines):
        if l.startswith(prefix):
            hit = i
            break
    if hit < 0:
        print("❌ %s 没找到 %s" % (path, prefix))
        sys.exit(1)
    old = lines[hit]
    lines[hit] = "const APP_VER = '20261007dt'; // " + NEW_NOTE
    with io.open(path, "w", encoding="utf-8", newline="") as f:
        f.write("\n".join(lines))
    print("✓ %s L%d  %s → %s" % (path, hit + 1, old[:38], lines[hit][:38]))
