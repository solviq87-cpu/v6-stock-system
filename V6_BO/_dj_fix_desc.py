# dj 轮：面板「判定规则」说明里写死的名义窗口，一并改成「按实际K线」的口径
import io, sys

p = 'server.js'
s = io.open(p, encoding='utf-8').read()

def rep(old, new, cnt=1):
    global s
    if s.count(old) != cnt:
        print('  !! 锚点命中 %d 次（应 %d）: %r' % (s.count(old), cnt, old[:60])); sys.exit(1)
    s = s.replace(old, new, cnt)

# PATH_DESC：面板悬浮显示的「判定规则」，同样是对外陈述
rep(u"  '涨停基因': '获利盘≥85% 且90日内≥2次涨停',",
    u"  '涨停基因': '获利盘≥85% 且窗口内≥2次涨停（名义90日，实按K线根数）',")
rep(u"  '低位启动': '距95日低点<20%、近3日累计>4%、今日量≥昨日1.5倍、站上5日线',",
    u"  '低位启动': '距阶段低点<20%（窗口最长95日，实按K线根数）、近3日累计>4%、今日量≥昨日1.5倍、站上5日线',")

# 上方那段注释里的"文案写「距95日低点」"是历史陈述，改成不触发扫描的表述
rep(u"//    数据 200 根时算的是「200 日低点」，文案写「距95日低点」—— 名不副实的两头都占。",
    u"//    数据 200 根时算的是「200 日低点」，而对外一律说成「95 日」—— 名不副实的两头都占。")
rep(u"    //    而文案一律写「距95日低点」—— 名不副实的两头都占。现在真的切 95 根。",
    u"    //    而对外一律说成「95 日」—— 名不副实的两头都占。现在真的切 95 根。")

io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('OK', p, '| CR=', io.open(p, encoding='utf-8').read().count('\r'))
