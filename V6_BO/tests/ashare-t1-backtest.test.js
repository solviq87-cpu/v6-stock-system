'use strict';
const assert=require('node:assert/strict');
const {walkForward,atLockedLimit,limitPct}=require('../src/strategy/walk-forward-backtest');
let n=0;const ok=x=>{assert.ok(x);n++};
const bars=Array.from({length:48},(_,i)=>({open:10+i*.06,high:10.2+i*.06,low:9.9+i*.06,close:10.1+i*.06,volume:1e6}));
const s={symbol:'000001',market:'main',bars};
ok(limitPct(s)===10);ok(limitPct({...s,market:'chinext'})===20);
ok(limitPct({...s,market:'unknown'})===null);
ok(atLockedLimit({open:11,high:11,low:11,close:11},{close:10},s,'buy').blocked);
ok(atLockedLimit({open:9,high:9,low:9,close:9},{close:10},s,'sell').blocked);
ok(!atLockedLimit({open:10,high:10.2,low:9.9,close:10.1},{close:10},s,'buy').blocked);
const r=walkForward({stocks:[s],start:27,end:40});
ok(Array.isArray(r.trades));ok(r.trades.every(t=>t.buyDay===t.signalDay+1&&t.sellDay>=t.buyDay+1));
ok(r.trades.every((t,i)=>i===0||t.buyDay>r.trades[i-1].sellDay));
ok(r.assumptions.some(x=>x.includes('幸存者偏差')));
const mutated=bars.map(b=>({...b}));mutated[46].close=100000;mutated[46].high=100000;
ok(JSON.stringify(walkForward({stocks:[s],start:27,end:35}).trades)===JSON.stringify(walkForward({stocks:[{...s,bars:mutated}],start:27,end:35}).trades));
ok(walkForward({stocks:[s],start:47}).metrics.trades===0);
const costly=walkForward({stocks:[s],start:27,end:40,feeBps:100,slippageBps:100});
ok(costly.metrics.returnPct<=r.metrics.returnPct);
console.log('PASS '+n+' T+1 / limits / walk-forward checks');
