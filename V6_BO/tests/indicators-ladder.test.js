'use strict';
const assert=require('node:assert/strict');
const {barsToIndicators}=require('../src/strategy/historical-indicators');
const {classifyLimitLadder,rankLadderCandidates}=require('../src/strategy/limit-ladder-engine');
let checks=0;const ok=(x)=>{assert.ok(x);checks++;};
const bars=Array.from({length:40},(_,i)=>({open:10+i*.1,high:10.3+i*.1,low:9.8+i*.1,close:10.1+i*.1,volume:1e6+i*1000}));
const ind=barsToIndicators(bars);
ok(ind.valid&&ind.ready);ok(Number.isFinite(ind.macd.hist));ok(ind.rsi14>=0&&ind.rsi14<=100);
ok(ind.ma5>ind.ma10&&ind.ma10>ind.ma20);ok(ind.volumeRatio>0);
ok(!barsToIndicators([{open:1,high:0,low:1,close:1,volume:5}]).valid);
ok(barsToIndicators([]).valid===false);
const base=bars.map(x=>({...x}));
const prior=base.at(-1).close;
base.push({open:prior*1.02,high:prior*1.1,low:prior*1.01,close:prior*1.1,volume:2e6});
const first=classifyLimitLadder({bars:base,market:'main'});
ok(first.stage==='首板'&&first.streak===1);ok(first.next==='一进二候选');ok(first.autoTrade===false);
const prev=base.at(-1).close;
base.push({open:prev*1.03,high:prev*1.1,low:prev*1.02,close:prev*1.1,volume:3e6});
const second=classifyLimitLadder({bars:base,market:'main'});
ok(second.stage==='二板'&&second.next==='二进三候选');
ok(classifyLimitLadder({bars:base,market:'unknown'}).eligible===false);
ok(classifyLimitLadder({bars:base,isST:true}).eligible===false);
ok(classifyLimitLadder({bars:base.slice(0,10)}).eligible===false);
ok(rankLadderCandidates([{symbol:'A',bars:base},{symbol:'B',bars:base.slice(0,5)}])[0].symbol==='A');
console.log('PASS '+checks+' historical indicators and limit ladder assertions');
