'use strict';
const assert=require('node:assert/strict');
const {evaluateCandidate,rankCandidates}=require('../src/strategy/strategy-service');
let n=0;const check=v=>{assert.ok(v);n++};
const bars=Array.from({length:40},(_,i)=>({open:10+i*.1,high:10.3+i*.1,low:9.8+i*.1,close:10.1+i*.1,volume:1e6}));
const candidate=evaluateCandidate({stock:{code:'000001',bars,leaderStrengthScore:85,sectorHeatScore:80,resealScore:80,sealQualityScore:90,moneyPersistenceScore:80,fundFlowScore:80}});
check(candidate.playbookAnalysis.playbooks.length===10);
check(candidate.playbookAnalysis.matched>=3);
check(candidate.playbookAnalysis.playbooks.find(x=>x.id==='leader_sector').status==='candidate');
check(candidate.playbookAnalysis.playbooks.find(x=>x.id==='first_to_second').status!=='candidate');
check(candidate.playbookAnalysis.playbooks.every(x=>x.autoTrade===false));
const empty=evaluateCandidate({stock:{code:'000002'}});
check(empty.playbookAnalysis.matched===0);
check(empty.playbookAnalysis.playbooks.some(x=>x.status==='insufficient_data'));
check(Number.isFinite(empty.finalScore));
const ranked=rankCandidates({stocks:[{code:'000002'},{code:'000001',bars,leaderStrengthScore:85,sectorHeatScore:80}]});
check(ranked.length===2);
check(ranked.every(x=>x.playbookAnalysis));
check(ranked.every(x=>typeof x.pass==='boolean'));
check(ranked.every(x=>Number.isFinite(x.finalScore)));
console.log('PASS '+n+' integrated playbook ranking assertions');
