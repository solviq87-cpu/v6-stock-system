 'use strict';
const assert=require('node:assert/strict');
const {validateFeed}=require('../src/strategy/feed-quality');
const {scanUniverse}=require('../src/strategy/universe-scanner');
const {walkForward}=require('../src/strategy/walk-forward-backtest');
let n=0;const ok=x=>{assert.ok(x);n++;};
const now=Date.UTC(2026,10,4),bars=Array.from({length:45},(_,i)=>({date:new Date(Date.UTC(2026,8,1+i)).toISOString().slice(0,10),open:10+i*.08,high:10.3+i*.08,low:9.8+i*.08,close:10.1+i*.08,volume:1e6}));
const stock={symbol:'000001',market:'main',bars,feed:{source:'simulated',timestamp:now}};
const q=validateFeed(stock,{now});ok(q.usable);ok(q.simulated);ok(q.warnings.some(x=>x.includes('模拟')));
ok(!validateFeed(stock,{now,requireReal:true}).usable);
ok(!validateFeed({...stock,feed:{source:'unknown',timestamp:now}},{now}).usable);
ok(!validateFeed({...stock,feed:{source:'eastmoney',timestamp:now-3600000}},{now}).fresh);
ok(!validateFeed({...stock,close:1},{now}).usable);
ok(!validateFeed({...stock,bars:bars.slice(0,10)},{now}).usable);
const ranked=scanUniverse({stocks:[stock,{...stock,symbol:'000002',feed:{source:'eastmoney',timestamp:now-3600000}}],now});
ok(ranked.total===2);ok(ranked.items[0].symbol==='000001');ok(ranked.items[0].strategy.playbookAnalysis.playbooks.length===10);
ok(ranked.items[1].tradable===false);ok(ranked.simulated===1);
ok(scanUniverse({stocks:[stock,stock],now}).rejected===1);
ok(scanUniverse({stocks:[stock],now,requireReal:true}).eligible===0);
const base=walkForward({stocks:[stock],start:27,end:40,feeBps:8,slippageBps:10});
ok(base.equity.length===8);ok(base.trades.every(t=>t.buyDay===t.signalDay+1));
ok(Number.isFinite(base.metrics.returnPct));ok(base.metrics.maxDrawdownPct>=0);
const costly=walkForward({stocks:[stock],start:27,end:40,feeBps:100,slippageBps:100});
ok(costly.metrics.returnPct<=base.metrics.returnPct);
const noFuture=walkForward({stocks:[stock],start:27,end:35});
const mutated=bars.map(x=>({...x}));mutated[43].close=100000;mutated[43].high=100000;
const unchanged=walkForward({stocks:[{...stock,bars:mutated}],start:27,end:35});
ok(JSON.stringify(noFuture.trades)===JSON.stringify(unchanged.trades));
ok(walkForward({stocks:[stock],start:45}).metrics.trades===0);
console.log('PASS '+n+' feed/scan/backtest assertions');
