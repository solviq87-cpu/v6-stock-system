'use strict';
const assert=require('node:assert/strict');
const {ledgerBacktest}=require('../src/strategy/position-ledger-backtest');
const {scanUniverse}=require('../src/strategy/universe-scanner');
const {validateFeed}=require('../src/strategy/feed-quality');
let checks=0;const ok=(x,m)=>{assert.ok(x,m);checks++};
const mk=(symbol)=>({symbol,market:'main',bars:Array.from({length:46},(_,i)=>{
 const close=+(10+i*.05).toFixed(3);
 return {open:close,high:close+.1,low:close-.1,close,volume:1000000,date:new Date(Date.UTC(2026,0,i+1)).toISOString().slice(0,10)};
})});
const s=mk('000001'),selector=()=>['000001'];
const opts={stocks:[s],start:27,end:40,selectCandidates:selector};
const a=ledgerBacktest(opts);
ok(a.trades.length>0,'必须有真实模拟成交');
ok(a.orders.some(x=>x.side==='buy'&&x.status==='filled'));
ok(a.orders.some(x=>x.side==='sell'&&x.status==='filled'));
ok(a.trades.every(t=>t.sellDay>t.buyDay),'T+1');
ok(a.equity.every(e=>e.value>0&&e.cash>=0));
ok(a.metrics.closedTrades===a.trades.length);
ok(a.dataProvenance.mode==='test-selector');
const fee=ledgerBacktest({...opts,feeBps:100,slippageBps:100,sellTaxBps:100});
ok(fee.metrics.finalEquity<a.metrics.finalEquity,'成本应降低净值');
const fut=mk('000001');fut.bars[45].close=99999;
ok(JSON.stringify(ledgerBacktest({...opts,stocks:[fut]}).equity)===JSON.stringify(a.equity),'未来数据泄漏');
const locked=mk('000001');
locked.bars[29]={...locked.bars[29],open:10.26,high:10.26,low:10.26,close:10.26};
const b=ledgerBacktest({...opts,stocks:[locked],end:33});
ok(b.orders.some(o=>o.side==='sell'&&o.status==='blocked'),'跌停卖出受阻');
ok(b.equity.find(e=>e.day===29).openPositions===1,'受阻必须继续持有');
ok(b.orders.some(o=>o.side==='sell'&&o.status==='filled'&&o.day>29),'后续继续卖出');
const st=mk('000001');st.isST=true;
ok(!ledgerBacktest({...opts,stocks:[st]}).orders.some(o=>o.side==='buy'&&o.status==='filled'),'ST不得买入');
const noVolume=mk('000001');noVolume.bars[28].volume=0;
ok(!ledgerBacktest({...opts,stocks:[noVolume],end:28}).orders.some(o=>o.side==='buy'&&o.status==='filled'),'零成交不可买入');
const timestamp=Date.UTC(2026,0,30),valid={...s,feed:{source:'imported',timestamp}};
ok(validateFeed(valid,{now:timestamp}).usable);
const duplicate=mk('000002');duplicate.bars[18].date=duplicate.bars[17].date;
ok(!validateFeed({...duplicate,feed:{source:'imported',timestamp}},{now:timestamp}).usable,'历史日期重复必须拒绝');
const universe=scanUniverse({stocks:[valid],now:timestamp});
ok(universe.total===1);ok(universe.items[0].quality.source==='imported');
ok(universe.items[0].strategy!==null,'扫描器应产出原策略信息');
ok(universe.items[0].strategy.playbookAnalysis.playbooks.length===10,'战法接入扫描');
ok(universe.items[0].ladder!==null,'连板分析接入扫描');
assert.throws(()=>ledgerBacktest({...opts,selectCandidates:'bad'}));checks++;
assert.throws(()=>ledgerBacktest({...opts,initialCash:-1}));checks++;
console.log('PASS '+checks+' integration assertions');
